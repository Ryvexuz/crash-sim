/// Same CSV through an explicitly chosen `SymplecticEuler`, and through `run_checked`.
#[test]
fn explicit_default_solver_is_the_default() {
    let cfg = Config::default();
    let mut a = Sim::new(cfg.clone());
    let mut b = Sim::with_solver(cfg, Box::new(SymplecticEuler::default()));
    for _ in 0..200 {
        a.advance();
        b.advance();
    }
    for i in 0..a.pos.len() {
        assert_eq!(a.pos[i], b.pos[i]);
        assert_eq!(a.vel[i], b.vel[i]);
    }
}

/// A test-only velocity-Verlet solver (half kick, drift, half kick). It shares nothing with
/// `SymplecticEuler` but the trait. No ground contact: the test stops before the drop ends.
struct VelocityVerlet {
    calls: Rc<Cell<u64>>,
}

fn forces(pos: &[Vec3], vel: &[Vec3], beams: &[Beam], mass: &[f64], gravity: f64) -> Vec<Vec3> {
    let mut f: Vec<Vec3> = mass.iter().map(|&m| Vec3::new(0.0, -gravity * m, 0.0)).collect();
    for b in beams {
        let d = pos[b.b] - pos[b.a];
        let len = d.length();
        let dir = d * (1.0 / len);
        let mag = b.stiffness * (len - b.rest) + b.damping * (vel[b.b] - vel[b.a]).dot(dir);
        f[b.a] += dir * mag;
        f[b.b] += -(dir * mag);
    }
    f
}

impl Solver for VelocityVerlet {
    fn step(&mut self, s: State<'_>, h: f64) {
        self.calls.set(self.calls.get() + 1);
        let State { pos, vel, beams, mass, gravity } = s;
        let f0 = forces(pos, vel, beams, mass, gravity);
        for i in 0..pos.len() {
            vel[i] += f0[i] * (0.5 * h / mass[i]);
            pos[i] += vel[i] * h;
        }
        let f1 = forces(pos, vel, beams, mass, gravity);
        for i in 0..pos.len() {
            vel[i] += f1[i] * (0.5 * h / mass[i]);
        }
    }
}

#[test]
fn a_second_solver_plugs_in() {
    // 0.5 s of the default drop: the cube is still in the air (first contact is at 0.639 s).
    let cfg = Config { duration: 0.5, ..Config::default() };
    let steps = (cfg.duration / cfg.dt).round() as u64;
    let calls = Rc::new(Cell::new(0));
    let mut sim = Sim::with_solver(cfg.clone(), Box::new(VelocityVerlet { calls: calls.clone() }));
    let mut reference = Sim::new(cfg.clone());
    let mut other = vec![sim.sample()];
    let mut base = vec![reference.sample()];
    for _ in 0..steps {
        sim.advance();
        reference.advance();
        sim.check().expect("second solver stays valid");
        other.push(sim.sample());
        base.push(reference.sample());
    }
    // The sim really called the solver, once per substep.
    assert_eq!(calls.get(), steps * cfg.substeps as u64);
    // A different integrator gives different bytes ...
    let (a, b) = (to_csv(&other), to_csv(&base));
    assert_ne!(a, b, "the second solver gave the same CSV as symplectic Euler: it is not being used");
    // ... for the same physics: close to it, not a different problem. Symplectic Euler's
    // free fall lags the exact one by g h t / 2 = 2.5 mm at t = 0.5 s, h = 1 ms.
    let worst = other.iter().zip(&base).map(|(x, y)| (x.center_y - y.center_y).abs()).fold(0.0, f64::max);
    assert!(worst < 5e-3, "second solver diverges from symplectic Euler: {worst}");
    assert!(worst > 0.0);
    // Free fall: after 0.5 s every node has fallen g t^2 / 2 within the beams' tiny strain.
    let fell = other[0].center_y - other.last().unwrap().center_y;
    assert!((fell - 9.81 * 0.25 / 2.0).abs() < 1e-3, "fell {fell}");
}

#[test]
fn mass_and_material_are_data_on_the_state() {
    let sim = Sim::new(Config::default());
    assert_eq!(sim.mass.len(), sim.pos.len());
    assert!(sim.mass.iter().all(|&m| m == NODE_MASS));
    assert_eq!(sim.beams.len(), 28);
    assert!(sim.beams.iter().all(|b| b.stiffness == BEAM_STIFFNESS && b.damping == BEAM_DAMPING));
    // The step-limit checks read the state and give today's numbers for the cube.
    let (k, c, m) = step_limit_params(&sim.beams, &sim.mass);
    assert_eq!((k, c, m), (BEAM_STIFFNESS, BEAM_DAMPING, NODE_MASS));
    let limit = stable_step_limit(k, c, m);
    assert!((limit - 0.0041).abs() < 5e-5, "{limit}");
    // And the refusal text for a too-large step is exactly what main printed.
    let too_big = Config { substeps: 1, ..Config::default() };
    assert_eq!(too_big.validate().unwrap_err(), STEP_REFUSAL_ON_MAIN);
}

#[test]
fn step_limit_follows_the_lightest_node_and_stiffest_beam() {
    // Not the cube: a lighter node or a stiffer beam must move the limit.
    let mut sim = Sim::new(Config::default());
    sim.mass[3] = 0.25;
    sim.beams[5].stiffness = 80_000.0;
    sim.beams[6].damping = 50.0;
    assert_eq!(step_limit_params(&sim.beams, &sim.mass), (80_000.0, 50.0, 0.25));
    let cube = Sim::new(Config::default());
    let g = |s: &Sim| solver::gershgorin_step_limit(s.mass.len(), &s.beams, &s.mass);
    assert!(g(&sim) < g(&cube));
}

#[test]
fn symplectic_euler_uses_per_node_mass_and_per_beam_stiffness() {
    // Two nodes, one stretched beam, no gravity: dv = F / m * h, so 4x mass gives 1/4 speed.
    let run_with = |m: f64, k: f64| {
        let mut pos = vec![Vec3::new(0.0, 5.0, 0.0), Vec3::new(1.5, 5.0, 0.0)];
        let mut vel = vec![Vec3::ZERO; 2];
        let beams = [Beam { a: 0, b: 1, rest: 1.0, stiffness: k, damping: 0.0 }];
        let mass = [m, m];
        SymplecticEuler::default().step(State { pos: &mut pos, vel: &mut vel, beams: &beams, mass: &mass, gravity: 0.0 }, 0.001);
        vel[0].x
    };
    let light = run_with(1.0, 1000.0);
    assert!((light - 0.5 * 1000.0 * 0.001).abs() < 1e-12, "{light}");
    assert!((run_with(4.0, 1000.0) - light / 4.0).abs() < 1e-12);
    assert!((run_with(1.0, 2000.0) - light * 2.0).abs() < 1e-12);
}

