    let samples = run(&Config::default());
    let csv = to_csv(&samples);
    assert_eq!(csv.len(), DEFAULT_CSV.len(), "CSV length differs from the fixture captured on main");
    assert!(csv == DEFAULT_CSV, "default CSV differs from the fixture captured on main (b0d237d)");
